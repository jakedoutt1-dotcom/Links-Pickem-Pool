import assert from 'node:assert/strict';
import {createActionLog, renderActionLog} from '../public/new-build/poker-action-log.mjs';
const log = createActionLog({limit: 3});
const table = {id: 'one', handNumber: 1, actionNumber: 1, players: [{id: 'a',name: '<img onerror=bad>'}],lastAction:{playerId:'a',type:'raise',amount:75,to:100}};
let entries = log.update('ROOM',table);
assert.equal(entries[0].text,'<img onerror=bad> raises to 100');
assert.equal(log.update('ROOM',table).length,1,'Polling repeats do not duplicate actions');
table.actionNumber = 3; table.lastAction = {playerId:'a',type:'call',amount:50,to:150,allIn:true};
entries=log.update('ROOM',table);
assert.equal(entries.length,2,'Missed polls never fabricate actions');
assert.equal(entries[0].text,'<img onerror=bad> calls 50 · all-in');
table.actionNumber = 2;
assert.equal(log.update('ROOM',table).length,2,'Older responses do not add stale actions');
table.actionNumber=4;table.lastAction={playerId:'a',type:'check',timeout:true};
assert.equal(log.update('ROOM',table)[0].text,'<img onerror=bad> checks · timer expired');
table.actionNumber=5;table.lastAction={playerId:'a',type:'fold'};
assert.equal(log.update('ROOM',table).length,3,'List is bounded');
table.handNumber++;table.lastAction=null;
assert.deepEqual(log.update('ROOM',table),[],'A new hand clears the list');
table.lastAction={playerId:'a',type:'fold'};
assert.equal(log.update('ROOM',table).length,1);
assert.equal(log.update('OTHERROOM',table).length,1,'Room scope resets even with same table and hand');
table.id='two';table.lastAction=null;
assert.deepEqual(log.update('OTHERROOM',table),[]);
table.lastAction={playerId:'a',type:'raise',amount:12,to:Infinity};table.actionNumber++;
assert.deepEqual(log.update('OTHERROOM',table),[],'Invalid public chip amounts are ignored');
assert.deepEqual(log.update('OTHERROOM',null),[]);
const list={dataset:{},ownerDocument:{createElement:()=>({})},replaceChildren(...children){this.rows=children;}};
renderActionLog(list,entries);
assert.equal(list.rows[1].textContent,'<img onerror=bad> raises to 100','Names are rendered as literal text');
assert.equal(list.rows[1].innerHTML,undefined);
renderActionLog(list,[]);
assert.match(list.rows[0].textContent,/New actions/);
console.log('PASS observed poker action log: amounts, deduplication, scope resets, bounded rows and safe rendering.');
